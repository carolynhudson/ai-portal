"""The Windows forge kit ships to a box we do not control, running
Windows PowerShell 5.1. Three run failures on RainbowBlock.local taught
the kit's hard rules (journal 6.14.1p): UTF-8 punctuation arrives as ANSI
mojibake and breaks quoting; PS7-only syntax (ternary, null-coalescing)
is a parse error on 5.1; multi-line expressions inside throw(...) break
under 5.1's parser. The rules are ASCII and 5.1-safety - this file keeps
them true for every future edit, and pins the parse preflight the owner
runs first on the target box."""
from __future__ import annotations

import json
import re
from pathlib import Path

KIT = Path(__file__).resolve().parents[1] / "deploy" / "windows-forge"

# PS7-only syntax that Windows PowerShell 5.1 cannot parse. The ternary
# pattern needs a real operand context ('x ? a : b'); a lone '?' in prose
# inside a string is caught by the owner's parse preflight anyway.
PS7_ONLY = [
    re.compile(r"\)\s*\?|\]\s*\?|\w\s*\?\s*[^:\s]", re.MULTILINE),  # 'a ? b : c'
    re.compile(r"\?\?"),                                             # null-coalescing
    re.compile(r"-\?|\$\{[^}]*\?\}"),                                # ternary in interpolation
]


def scripts():
    return sorted(KIT.glob("*.ps1"))


def test_the_kit_is_pure_ascii():
    """5.1 reads scripts as ANSI: a UTF-8 em-dash arrives as three
    mojibake bytes, breaks string quoting, cascades into parse errors
    (owner's first run). ASCII parses identically under any code page -
    and no BOM either, the kit rule is plain bytes."""
    assert scripts(), "the kit has no .ps1 files"
    for ps1 in scripts():
        data = ps1.read_bytes()
        assert not data.startswith(b"\xef\xbb\xbf"), f"{ps1.name}: BOM is not plain ASCII bytes"
        bad = [i for i, b in enumerate(data) if b > 127]
        assert not bad, (
            f"{ps1.name}: {len(bad)} non-ASCII byte(s) at {bad[:5]} - "
            "see README 'File encoding'; keep the kit pure ASCII")


def test_the_kit_parses_under_powershell_5_1():
    """No PS7-only constructs: 5.1 chokes on the ternary and '??' with
    'Unexpected token' (owner's second run). The ternary net also catches
    encoding fossils - a '§' that an ASCII pass scrubbed to a bare '?'
    (found in start_comfyui.ps1's header comment): plain ASCII, but it
    reads as mojibake and the kit rule's whole point is readable files."""
    for ps1 in scripts():
        text = ps1.read_text()
        for pat in PS7_ONLY:
            m = pat.search(text)
            assert not m, (
                f"{ps1.name}: PS7-only construct {m.group(0)!r} - "
                "the target shell is Windows PowerShell 5.1")


def test_the_parse_preflight_ships_with_the_kit():
    """The owner runs parse_check.ps1 FIRST on RainbowBlock.local: it
    reports every parse failure (per line) before any installer touches
    the disk. It must parse files via the PowerShell parser - not
    execute them - and the README must tell the owner to run it.

    The parser type is pinned by name: the modern surface is
    Language.Parser::ParseInput (v3+); the legacy PSParser class only
    has Tokenize, and calling ParseInput on it is 'MethodNotFound' -
    which is how this script itself first failed on the target box."""
    pc = KIT / "parse_check.ps1"
    assert pc.is_file(), "the parse preflight must ship in the kit"
    text = pc.read_text()
    assert "Language.Parser]::ParseInput" in text, (
        "ParseInput lives on Language.Parser; PSParser has only Tokenize")
    assert "PSParser]::ParseInput" not in text, "the legacy PSParser has no ParseInput"
    assert "$($PSVersionTable.PSVersion)" in text, (
        "interpolating the whole $PSVersionTable prints 'Hashtable', not a version")
    assert "Extent.StartLineNumber" in text, (
        "ParseError carries Extent.StartLineNumber (the legacy Token.StartLine does not)")
    assert "Get-ChildItem" in text and "*.ps1" in text, "it must sweep every .ps1"
    assert re.search(r"exit\s+1", text), "parse failures must reach a nonzero exit code"
    readme = (KIT / "README.md").read_text()
    assert "parse_check.ps1" in readme, "the steps must tell the owner to run the preflight"


AGENT = Path(__file__).resolve().parents[1] / "deploy" / "windows-agent"


def test_the_agent_config_carries_only_the_resident_model():
    """The router runs --models-max 1: one resident model, every other
    catalog id is a swap (unload the portal controller's brain, load the
    request). So the agent config lists the resident model and nothing
    else, at its real context - generated by tools/sync_agent_models.py
    from the live router, never hand-picked. Pins: exactly one model; it
    is the resident (cache worker: the worker's --hf-repo; library worker:
    the --model file's directory - the post-migration shape) when the
    router is up; context is native-scale, not an invented cap; no hand-listed
    favorites (Qwopus/IQ1_M/DeepSeek/ThinkingCap); LAN IP, not a name;
    apiKey is the placeholder, no secret material."""
    cfg = json.loads((AGENT / "opencode.json").read_text())
    prov = cfg["provider"]["llamarouter"]
    assert prov["npm"] == "@ai-sdk/openai-compatible"
    assert prov["options"]["baseURL"] == "http://127.0.0.1:8080/v1".replace(
        "127.0.0.1", "192.168.1.228")
    assert prov["options"]["apiKey"] == "local", "placeholder only - no secrets in the kit"
    models = prov["models"]
    assert len(models) == 1, (
        "--models-max 1: anything besides the resident model is a swap; "
        "the config is generated, regenerate it after a model change")
    (cid, entry), = models.items()
    assert cfg["model"] == "llamarouter/" + cid
    assert entry["limit"]["context"] >= 65536, (
        "the resident window is native (262k for the Swift family) - "
        "an invented cap makes opencode compact the agent mid-mission")
    assert entry.get("tool_call") is True
    blob = json.dumps(cfg)
    for favorite in ("IQ1_M", "Qwopus", "DeepSeek", "ThinkingCap", "Q8_0"):
        assert favorite not in blob, f"{favorite} hand-listed again: with models-max 1 that is a swap"
    assert "halo.local" not in blob, "pin the static lease IP, not the name"
    # When the router is up, the config must match what is actually resident.
    # Two worker shapes (post-migration law): cache-sourced carries
    # --hf-repo (the id IS repo:tag); library-sourced carries --model
    # <path under the llama library> and is served under its directory name.
    import subprocess
    from pathlib import Path as _P
    try:
        ps = subprocess.run(["ps", "-eo", "args"], capture_output=True,
                            text=True, timeout=10).stdout
    except Exception:
        return
    libroot = str(_P.home() / "ai/models/llama") + "/"
    for line in ps.splitlines():
        if "llama-server" not in line:
            continue
        if "--hf-repo" in line and "--alias" in line:
            repo = line.split("--hf-repo")[1].split()[0]
            assert cid == repo, f"config lists {cid!r} but {repo!r} is resident - regenerate"
            return
        if "--model " in line:
            p = _P(line.split("--model ")[1].split()[0]).resolve()
            if str(p).startswith(libroot):
                assert cid == p.parent.name, (
                    f"config lists {cid!r} but the library worker serves "
                    f"{p.parent.name!r} - regenerate")
                return


def test_the_model_config_is_generated_not_handwritten():
    """tools/sync_agent_models.py rebuilds the agent config from the
    live router (resident id, preset ctx, capability flags). Pins: it
    exists, reads the router truth (--hf-repo, presets.ini), builds via
    a pure function, and --print yields exactly the one-resident shape
    the config test pins (live router; skipped when the router is down)."""
    script = Path(__file__).resolve().parents[1] / "tools" / "sync_agent_models.py"
    assert script.is_file(), "the agent config must have a generator"
    text = script.read_text()
    for needle in ("--hf-repo", "--model", "presets.ini", "models-max 1", "build_config",
                   "merge_config"):
        assert needle in text, f"the generator lost {needle!r}"
    import subprocess
    import sys
    r = subprocess.run([sys.executable, str(script), "--print"],
                       capture_output=True, text=True, timeout=30)
    if r.returncode != 0:
        return  # router down: the generator refuses to guess, and so does this test
    cfg = json.loads(r.stdout)
    models = cfg["provider"]["llamarouter"]["models"]
    assert len(models) == 1, "generator produced more than the resident model"
    entry = next(iter(models.values()))
    assert entry["limit"]["context"] >= 65536


def test_the_kit_carries_no_credential_material():
    """2026-11-07 lesson: a folder copy from C:\\forge\\kit brought the box's
    live secrets into the repo — the agent server's Basic-auth password
    (agent_server.json) and the pasted mesh token (a real Bearer in
    opencode.json). The kit's law is placeholder tokens and box-local state;
    this scan is the net that catches the next well-meant copy. The mesh
    token, not the password, is the one that keeps working across rotations,
    so neither is ever allowed here."""
    import re
    secret = re.compile(r"Bearer\s+(?!PASTE-TOKEN)[A-Za-z0-9_\-\.]{20,}"
                        r"|password[\"']?\s*[:=]\s*[\"']?[A-Za-z0-9][^\s\"']{11,}")
    for p in sorted(AGENT.rglob("*")):
        if not p.is_file() or p.name == ".gitignore":
            continue
        assert p.name != "agent_server.json", \
            "box-local agent state entered the repo (it carries the auth password)"
        t = p.read_text(errors="replace")
        hits = secret.findall(t)
        assert not hits, f"{p.name} carries credential material: {[h[:10] for h in hits]}"


def test_the_regen_merge_keeps_the_box_and_follows_the_router():
    """2026-11-07 lesson: the kit on RainbowBlock grew a forge-ops agent and
    a pasted mesh token; a regen that rewrote the whole file would silently
    evict both. The merge law: provider.llamarouter and the default model
    follow the router; everything the box added survives, token included."""
    import importlib.util
    spec = importlib.util.spec_from_file_location(
        "sync_agent_models",
        Path(__file__).resolve().parents[1] / "tools" / "sync_agent_models.py")
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    box = {
        "provider": {"llamarouter": {"models": {"ukisai/DEAD:IQ3_S": {}},
                                     "options": {"baseURL": "http://old/v1"}},
                     "somewhere-else": {"npm": "x"}},
        "model": "llamarouter/ukisai/DEAD:IQ3_S",
        "mcp": {"halo-kb": {"url": "http://192.168.1.228:8090/api/mcp",
                            "headers": {"Authorization": "Bearer REAL-PASTED"}}},
        "agent": {"forge-ops": {"permission": {"external_directory": "deny"}}},
    }
    gen = mod.build_config({"Swift-Flash-Next-IQ3_S": {"name": "resident"}})
    out = mod.merge_config(box, gen)
    assert list(out["provider"]["llamarouter"]["models"]) == ["Swift-Flash-Next-IQ3_S"], \
        "the model list must follow the router (the migration break)"
    assert out["model"] == "llamarouter/Swift-Flash-Next-IQ3_S"
    assert out["provider"]["somewhere-else"] == {"npm": "x"}, "a foreign provider survives"
    assert out["mcp"]["halo-kb"]["headers"]["Authorization"] == "Bearer REAL-PASTED", \
        "the pasted mesh token survives the regen"
    assert out["agent"]["forge-ops"]["permission"]["external_directory"] == "deny", \
        "the box's containment agent survives the regen"


