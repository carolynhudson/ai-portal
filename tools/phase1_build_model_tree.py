def main() -> None:
    ap_ = argparse.ArgumentParser()
    ap_.add_argument("--dry-run", action="store_true")
    args = ap_.parse_args()
    dry = args.dry_run

    # pre-flight: every source must exist
    missing = []
    for model, files in MODEL_TREE.items():
        for src, _ in files:
            if not src.resolve().is_file():
                missing.append(str(src))
    if missing:
        ap.die("missing sources:\n  " + "\n  ".join(missing))

    total_bytes = 0
    ap.log(f"building model tree at {ap.LLAMA_MODELS} (dry-run={dry})")
    for model, files in MODEL_TREE.items():
        for src, dst_name in files:
            dst_name = dst_name or src.name
            dst = ap.LLAMA_MODELS / model / dst_name
            st = ap.link_file(src, dst, dry)
            size = src.resolve().stat().st_size
            total_bytes += size if st == "linked" else 0
            ap.log(f"  [{st:8s}] {model}/{dst_name}  ({ap.human(size)})")

    ap.ensure_dir(ap.LLAMA_CONFIG, dry)
    if dry:
        ap.log(f"would write {ap.PRESETS_INI} ({len(PRESETS_INI)} bytes)")
    else:
        ap.PRESETS_INI.write_text(PRESETS_INI)
        ap.log(f"wrote {ap.PRESETS_INI}")

    ap.log(f"done. models={len(MODEL_TREE)} "
           f"new links this run used ~{ap.human(total_bytes)} (hardlinks: 0 disk)")


if __name__ == "__main__":
    main()
